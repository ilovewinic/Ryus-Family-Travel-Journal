-- 우리가족 여행기록장: 여행 기간, 여러 방문 장소, 여러 숙소 기록
-- 기존 journals / journal_photos / journal_expenses 데이터는 삭제하거나 변환하지 않는 확장 마이그레이션입니다.
-- Supabase SQL Editor에서 한 번 실행해 주세요.

alter table public.journals
  add column if not exists end_date date,
  add column if not exists companions text[] not null default '{}'::text[],
  add column if not exists transport text;

-- 한 여행에서 방문한 관광지·식당·카페·체험 장소 등을 각각 기록합니다.
create table if not exists public.journal_places (
  id bigint generated by default as identity primary key,
  client_id text not null unique,
  journal_id bigint not null references public.journals(id) on delete cascade,
  name text not null,
  category text not null default 'attraction',
  visit_date date,
  visit_time time,
  sequence integer not null default 0,
  address text,
  region text,
  latitude double precision,
  longitude double precision,
  memo text,
  rating smallint check (rating between 1 and 5),
  is_favorite boolean not null default false,
  visit_status text not null default 'visited'
    check (visit_status in ('visited', 'planned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists journal_places_journal_id_idx
  on public.journal_places(journal_id);
create index if not exists journal_places_name_idx
  on public.journal_places(name);
create index if not exists journal_places_visit_date_idx
  on public.journal_places(visit_date);

-- 숙소는 숙박 한 번을 한 행으로 기록합니다.
-- 같은 숙소에서 2박하면 체크인/체크아웃 날짜로 2박이 계산되고,
-- 한 여행에서 숙소를 옮겼다면 행을 여러 개 추가할 수 있습니다.
create table if not exists public.journal_stays (
  id bigint generated by default as identity primary key,
  client_id text not null unique,
  journal_id bigint not null references public.journals(id) on delete cascade,
  name text not null,
  check_in date not null,
  check_in_time time,
  check_out date not null,
  check_out_time time,
  address text,
  region text,
  latitude double precision,
  longitude double precision,
  memo text,
  rating smallint check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint journal_stays_valid_dates check (check_out >= check_in)
);

create index if not exists journal_stays_journal_id_idx
  on public.journal_stays(journal_id);
create index if not exists journal_stays_name_idx
  on public.journal_stays(name);

-- 사진과 경비를 특정 방문 장소/숙소에 연결할 수 있도록 선택형 연결 칸을 준비합니다.
alter table public.journal_photos
  add column if not exists place_client_id text
    references public.journal_places(client_id) on delete set null;
alter table public.journal_expenses
  add column if not exists place_client_id text
    references public.journal_places(client_id) on delete set null,
  add column if not exists stay_client_id text
    references public.journal_stays(client_id) on delete set null;

alter table public.journal_places enable row level security;
alter table public.journal_stays enable row level security;

drop policy if exists journal_places_select_family on public.journal_places;
create policy journal_places_select_family
  on public.journal_places
  for select to authenticated
  using (public.is_family_member());

drop policy if exists journal_places_insert_parent on public.journal_places;
create policy journal_places_insert_parent
  on public.journal_places
  for insert to authenticated
  with check (public.is_family_parent());

drop policy if exists journal_places_update_parent on public.journal_places;
create policy journal_places_update_parent
  on public.journal_places
  for update to authenticated
  using (public.is_family_parent())
  with check (public.is_family_parent());

drop policy if exists journal_places_delete_parent on public.journal_places;
create policy journal_places_delete_parent
  on public.journal_places
  for delete to authenticated
  using (public.is_family_parent());

drop policy if exists journal_stays_select_family on public.journal_stays;
create policy journal_stays_select_family
  on public.journal_stays
  for select to authenticated
  using (public.is_family_member());

drop policy if exists journal_stays_insert_parent on public.journal_stays;
create policy journal_stays_insert_parent
  on public.journal_stays
  for insert to authenticated
  with check (public.is_family_parent());

drop policy if exists journal_stays_update_parent on public.journal_stays;
create policy journal_stays_update_parent
  on public.journal_stays
  for update to authenticated
  using (public.is_family_parent())
  with check (public.is_family_parent());

drop policy if exists journal_stays_delete_parent on public.journal_stays;
create policy journal_stays_delete_parent
  on public.journal_stays
  for delete to authenticated
  using (public.is_family_parent());

grant select, insert, update, delete
  on public.journal_places, public.journal_stays
  to authenticated;

grant usage, select
  on sequence public.journal_places_id_seq, public.journal_stays_id_seq
  to authenticated;
